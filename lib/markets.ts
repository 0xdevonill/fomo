export function protocolTotals(markets: Market[]) {
  const supplied = markets.reduce((s, x) => s + x.totalSupplyUsd, 0);
  const borrowed = markets.reduce((s, x) => s + x.totalBorrowUsd, 0);
  return {
    supplied,
    borrowed,
    tvl: supplied,
    available: Math.max(0, supplied - borrowed),
  };
}
