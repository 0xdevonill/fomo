export function marketById(id: string): Market | undefined {
  const lower = id.toLowerCase();
  return MARKETS.find(
    (x) =>
      x.id === id ||
      x.id === lower ||
      x.symbol.toLowerCase() === lower ||
      x.address.toLowerCase() === lower
  );
}

export function overlayMarkets(live: LiveToken | null): Market[] {
  return MARKETS.map((mkt) => {
    if (!live || !mkt.featured) return mkt;
    const isPing =
      mkt.id === "ping" ||
      mkt.symbol.toUpperCase() === (site.tokenSymbol || "PING").toUpperCase();
    if (!isPing || !(live.priceUsd > 0)) return mkt;
    return {
      ...mkt,
      symbol: live.symbol || mkt.symbol,
      name: live.name || mkt.name,
      address: live.address || mkt.address,
      priceUsd: live.priceUsd,
    };
  });
}

